def reverse_template(
    *,
    head: Image.Image | None = None,
    body: Image.Image | None = None,
    legs: Image.Image | None = None,
    head_id: int | None = None,
    body_id: int | None = None,
    legs_id: int | None = None,
    set_name: str | None = None,
) -> ReverseResult:
    """Rebuild a 128x80 template from up to three Terraria armor textures."""
    template = new_canvas(*L.TEMPLATE_SIZE)
    warnings: list[str] = []

    if body is not None:
        _reverse_body(template, body, warnings)
    else:
        warnings.append("no body texture: the torso and the arms cannot be recovered")
    if head is not None:
        _reverse_head(template, head)
    else:
        warnings.append("no head texture: the head region is left empty")
    if legs is not None:
        _reverse_legs(template, legs)
    else:
        warnings.append("no legs texture: the legs region is left empty")

    return ReverseResult(
        template=template,
        head_id=head_id,
        body_id=body_id,
        legs_id=legs_id,
        set_name=set_name,
        warnings=warnings,
    )


# --------------------------------------------------------------------------- #
# Loading from a Terraria Content/Images folder
# --------------------------------------------------------------------------- #


def texture_paths(images_dir: str | Path, *, head: int | None, body: int | None, legs: int | None):
    """Locate the three textures, tolerating both known body folder layouts."""
    root = Path(images_dir)

    def find(*candidates: str) -> Path | None:
        for candidate in candidates:
            path = root / candidate
            if path.exists():
                return path
        return None

    return {
        "head": find(f"Armor_Head_{head}.png") if head is not None else None,
        "body": find(f"Armor/Armor_{body}.png", f"Armor_{body}.png")
        if body is not None
        else None,
        "legs": find(f"Armor_Legs_{legs}.png") if legs is not None else None,
    }


def load_texture(path: str | Path | None) -> Image.Image | None:
    if path is None:
        return None
    with Image.open(path) as image:
        return image.convert("RGBA")


def reverse_from_images(
    images_dir: str | Path,
    *,
    body: int,
    head: int | None = None,
    legs: int | None = None,
    set_name: str | None = None,
) -> ReverseResult:
    """Load the textures for the given armor ids and rebuild the template."""
    paths = texture_paths(images_dir, head=head, body=body, legs=legs)
    result = reverse_template(
        head=load_texture(paths["head"]),
        body=load_texture(paths["body"]),
        legs=load_texture(paths["legs"]),
        head_id=head,
        body_id=body,
        legs_id=legs,
        set_name=set_name,
    )
    for kind, path in paths.items():
        if path is None:
            label = {"head": head, "body": body, "legs": legs}[kind]
            if label is not None:
                result.warnings.append(f"Armor_{kind}_{label}.png not found in {images_dir}")
    return result
